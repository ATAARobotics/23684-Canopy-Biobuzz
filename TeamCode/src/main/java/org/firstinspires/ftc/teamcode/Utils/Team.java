package org.firstinspires.ftc.teamcode.Utils;

// Which alliance the robot is on. TeleOp subclasses return one of these from
// getTeam(), and the shared base TeleOp uses it to pick the starting pose and
// vision alliance letter.
public enum Team {
	BLUE,
	// Blue alliance side


	RED,
	// Red alliance side


	UNKNOWN
	// Team color not yet determined

}
